////////////////////////////////////////////////////////////////////////////////////////////

#include <cassert>
#include <sstream>
#include <string>

////////////////////////////////////////////////////////////////////////////////////////////

using namespace std::literals;

////////////////////////////////////////////////////////////////////////////////////////////

#include "08.02.hpp"

////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
	Integer x = std::string(32, '1');
	
	Integer y = std::string(32, '2');

//  ----------------------------------------------------------------------------------------

	assert((x += y) == "+33333333333333333333333333333333"s);

	assert((x -= y) == "+11111111111111111111111111111111"s);

	assert((x *= y) == "+246913580246913580246913580246908641975308641975308641975308642"s);

	assert((x /= y) == "+11111111111111111111111111111111"s);

//  ----------------------------------------------------------------------------------------

	assert((x ++  ) == "+11111111111111111111111111111111"s);

	assert((x --  ) == "+11111111111111111111111111111112"s);

	assert((  ++ y) == "+22222222222222222222222222222223"s);

	assert((  -- y) == "+22222222222222222222222222222222"s);

//  ----------------------------------------------------------------------------------------

	assert((x +  y) == "+33333333333333333333333333333333"s);

	assert((x -  y) == "-11111111111111111111111111111111"s);

	assert((x *  y) == "+246913580246913580246913580246908641975308641975308641975308642"s);

	assert((x /  y) == "+0"s);

//  ----------------------------------------------------------------------------------------

	assert((x <  y) == 1);

	assert((x >  y) == 0);

	assert((x <= y) == 1);

	assert((x >= y) == 0);

	assert((x == y) == 0);

	assert((x != y) == 1);

//  ----------------------------------------------------------------------------------------
	
	std::stringstream stream_1(std::string(32, '1'));

	std::stringstream stream_2;

//  ----------------------------------------------------------------------------------------
	
	stream_1 >> x;

	stream_2 << x;
	
//  ----------------------------------------------------------------------------------------
	
	assert(stream_2.str() == stream_1.str());

//  ----------------------------------------------------------------------------------------

	assert(sqrt(multiply(x, x)) == x);


    Integer x1 = 10;
	Integer y1 = 3;
    assert((x1 %= y1) == 1);

    Integer a(2);
    Integer b = a.pow(0);
    assert(b == Integer(1));

    Integer c = a.pow(1);
    assert(c == Integer(2));

    Integer d = a.pow(5);
    assert(d == Integer(32));

    Integer e = a.pow(10);
    assert(e == Integer(1024));

    Integer zero(0);
    Integer f = zero.pow(0);
    assert(f == Integer(1));

    Integer big("123456789");
    Integer m = big.pow(2);
    assert(m == big * big);

    Integer i(10);
    Integer j(-3);
     i %= j;
    assert(i == Integer(1));  // 10 % (-3) = 1

    Integer a1("987654321987654321");
    Integer b1("123456789");
    Integer quotient = a1 / b1;
    Integer remainder = a1 % b1;
    assert((quotient * b1) + remainder == a1);

    Integer a2(123);
    Integer a_abs = a2.abs();
    assert(a_abs == Integer(123));
    assert(a_abs.sign() == 1);

    Integer b2(0);
    Integer b_abs = b2.abs();
    assert(b_abs == Integer(0));
    assert(b_abs.sign() == 0);

    Integer c2(-123);
    Integer c_abs = c2.abs();
    assert(c_abs == Integer(123));
    assert(c_abs.sign() == 1);
}

